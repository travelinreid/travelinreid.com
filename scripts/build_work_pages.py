# ── HOMEPAGE PILLS ───────────────────────────────────────────────────

def update_homepage(projects):
    src = HOMEPAGE.read_text(encoding="utf-8")
    pills = "\n".join(
        f'      <a href="work/{html.escape(p["meta"]["slug"])}/" class="chip">{html.escape(p["meta"].get("pill", p["name"]))}</a>'
        for p in projects
    )
    block = f"{PILLS_START}\n{pills}\n      {PILLS_END}"
    if PILLS_START in src:
        new = re.sub(re.escape(PILLS_START) + r".*?" + re.escape(PILLS_END), lambda _: block, src, flags=re.S)
    else:
        new = re.sub(r'(<div class="projects-chips">)(.*?)(</div>)',
                     lambda m: f"{m.group(1)}\n      {block}\n    {m.group(3)}", src, count=1, flags=re.S)
    if new != src:
        HOMEPAGE.write_text(new, encoding="utf-8")


# ── MAIN ─────────────────────────────────────────────────────────────

def main():
    shared, projects = parse(SOURCE.read_text(encoding="utf-8"))
    if not projects:
        sys.exit("No projects found in content/works-in-progress.md")

    slugs = set()
    for p in projects:
        slug = p["meta"].get("slug") or re.sub(r"[^a-z0-9]+", "-", p["name"].lower()).strip("-")
        p["meta"]["slug"] = slug
        if slug in slugs:
            sys.exit(f"Two projects share the slug '{slug}'")
        slugs.add(slug)

    for i, p in enumerate(projects):
        out = OUT_DIR / p["meta"]["slug"] / "index.html"
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(page(p, i, projects, shared), encoding="utf-8")

        copy = " ".join([" ".join(p["meta"].get(k, "") for k in ("role", "started", "built_with"))]
                        + list(p["sections"].values()))
        n = len(find_placeholders(copy))
        if n:
            warn(f"{p['name']}: {n} [bracketed] placeholder{'s' if n != 1 else ''} left")

    # Remove pages for projects that were deleted from the copy doc
    if OUT_DIR.exists():
        for d in OUT_DIR.iterdir():
            f = d / "index.html"
            if d.is_dir() and d.name not in slugs and f.exists() and MARK in f.read_text(encoding="utf-8"):
                f.unlink()
                try:
                    d.rmdir()
                except OSError:
                    pass
                print(f"Removed work/{d.name}/ (no longer in the copy doc)")

    update_homepage(projects)

    print(f"Built {len(projects)} pages in work/ and updated the homepage pills.")
    if warnings:
        print(f"\n{len(warnings)} things still to fill in:")
        for w in warnings:
            print("  • " + w)


if __name__ == "__main__":
    main()
